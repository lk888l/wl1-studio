export const defaultParameterValues: ParameterValues = Object.fromEntries(
  parameterDefinitions.map((definition) => [definition.id, definition.defaultValue]),
);

export function formatParameterValue(definition: ParameterDefinition, value: number): string {
  return value.toFixed(definition.decimals);
}

export function buildParameterCommand(
  definition: ParameterDefinition,
  value: number,
): string | null {
  if (!definition.command || definition.support === "reserved") {
    return null;
  }
  const formatted = formatParameterValue(definition, value);
  return definition.flag
    ? `${definition.command} -${definition.flag} ${formatted}`
    : `${definition.command} ${formatted}`;
}
